def send_order_confirmation_sms(order):
    """
    ارسال پیامک تایید سفارش به کاربر.
    فعلاً فقط توی کنسول چاپ میشه (شبیه‌سازی) - بعداً می‌شه اینجا
    به یه سرویس پیامکی واقعی (مثل کاوه‌نگار) وصل کرد، بدون تغییر جای دیگه.
    """
    message = (
        f"{order.first_name} {order.last_name} عزیز، "
        f"سفارش شما ثبت شد و در اسرع وقت به دستتان خواهد رسید."
    )
    print(f"[SMS به سفارش #{order.id}]: {message}")  # شبیه‌سازی ارسال پیامک
    return message